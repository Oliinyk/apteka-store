function writeArtwork(name, svg) {
  mkdirSync(UPLOADS_DIR, { recursive: true });
  const file = path.join(UPLOADS_DIR, name);
  if (!existsSync(file)) writeFileSync(file, svg);
  return '/uploads/' + name;
}

export function seed() {
  const already = db.prepare('SELECT COUNT(*) AS n FROM products').get().n;

  for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
    if (!db.prepare('SELECT 1 FROM settings WHERE key = ?').get(key)) setSetting(key, value);
  }

  if (!db.prepare('SELECT 1 FROM users LIMIT 1').get()) {
    const { salt, hash } = hashPassword(process.env.ADMIN_PASSWORD || 'admin123');
    db.prepare('INSERT INTO users (username, hash, salt) VALUES (?, ?, ?)')
      .run(process.env.ADMIN_USER || 'admin', hash, salt);
  }

  writeArtwork('hero.svg', packArtwork({ title: getSetting('site.name', 'MASTENKO'), kicker: '', accent: '#1f8a70', bg: '#e4f1ec', kind: 'box' }));

  if (already > 0) return;

  const insertCat = db.prepare('INSERT OR IGNORE INTO categories (slug, title, description, sort) VALUES (?, ?, ?, ?)');
  for (const c of CATEGORIES) insertCat.run(c.slug, c.title, c.description, c.sort);

  const catId = {};
  for (const row of db.prepare('SELECT id, slug FROM categories').all()) catId[row.slug] = row.id;

  const insertProduct = db.prepare(`INSERT INTO products
    (slug, title, category_id, price, old_price, sku, stock, short_desc, description, specs, image, gallery, is_new, is_hit, active, sort, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?)`);

  P.forEach((p, i) => {
    const image = writeArtwork(`${p.slug}.svg`, packArtwork({
      title: p.title, kicker: CATEGORIES.find((c) => c.slug === p.cat).title,
      accent: p.accent, bg: p.bg, kind: p.kind,
    }));
    insertProduct.run(
      p.slug, p.title, catId[p.cat] ?? null, p.price, p.old_price || 0,
      'VT-' + String(1000 + i), p.stock ?? 0, p.short, p.desc,
      JSON.stringify(p.specs.map(([k, v]) => ({ k, v }))), image, '[]',
      p.is_new ? 1 : 0, p.is_hit ? 1 : 0, i, new Date().toISOString()
    );
  });

  const insertPage = db.prepare('INSERT OR IGNORE INTO pages (slug, title, content, in_menu, sort) VALUES (?, ?, ?, 1, ?)');
  for (const p of PAGES) insertPage.run(p.slug, p.title, p.content, p.sort);
}
